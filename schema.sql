CREATE TABLE IF NOT EXISTS items (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  name_key TEXT NOT NULL,
  qty REAL NOT NULL DEFAULT 1,
  unit TEXT NOT NULL DEFAULT 'pcs',
  category TEXT,
  bought TEXT,
  added TEXT NOT NULL,
  store TEXT,
  expiry TEXT,
  expiry_est INTEGER NOT NULL DEFAULT 0,
  finish_days INTEGER NOT NULL DEFAULT 14,
  learned INTEGER NOT NULL DEFAULT 0,
  source TEXT,
  area TEXT,
  essential INTEGER NOT NULL DEFAULT 0,
  low INTEGER NOT NULL DEFAULT 0,
  warn TEXT,
  note TEXT,
  owner TEXT,
  frozen INTEGER NOT NULL DEFAULT 0,
  unsure INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS items_name_key ON items(name_key);
CREATE TABLE IF NOT EXISTS purchases (
  name_key TEXT NOT NULL,
  bought TEXT NOT NULL,
  qty REAL,
  unit TEXT,
  ran_out TEXT,
  PRIMARY KEY (name_key, bought)
);
CREATE TABLE IF NOT EXISTS log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  at TEXT NOT NULL,
  source TEXT NOT NULL,
  summary TEXT NOT NULL,
  who TEXT
);
CREATE TABLE IF NOT EXISTS extras (
  id TEXT PRIMARY KEY,
  text TEXT NOT NULL,
  who TEXT,
  added TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pics (
  name_key TEXT PRIMARY KEY,
  data BLOB NOT NULL,
  made TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS spend (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  item_id TEXT,
  day TEXT NOT NULL,
  area TEXT,
  amount REAL NOT NULL,
  currency TEXT
);
CREATE TABLE IF NOT EXISTS settings (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS feedback (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  at TEXT NOT NULL,
  kind TEXT NOT NULL,
  said TEXT,
  reply TEXT,
  route TEXT,
  detail TEXT
);
CREATE TABLE IF NOT EXISTS push_subs (
  endpoint TEXT PRIMARY KEY,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  who TEXT,
  tz TEXT NOT NULL DEFAULT 'UTC',
  added TEXT NOT NULL,
  last_day TEXT,
  fails INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS reminders (
  name_key TEXT PRIMARY KEY,
  sent INTEGER NOT NULL DEFAULT 0,
  streak INTEGER NOT NULL DEFAULT 0,
  muted INTEGER NOT NULL DEFAULT 0,
  answered INTEGER NOT NULL DEFAULT 1,
  last_day TEXT
);
CREATE TABLE IF NOT EXISTS turns (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  at TEXT NOT NULL,
  said TEXT,
  route TEXT,
  intent TEXT,
  did TEXT,
  reply TEXT,
  outcome TEXT,
  wanted TEXT,
  label TEXT
);
CREATE TABLE IF NOT EXISTS cases (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  at TEXT NOT NULL,
  said TEXT NOT NULL UNIQUE,
  expect TEXT NOT NULL,
  name TEXT
);
